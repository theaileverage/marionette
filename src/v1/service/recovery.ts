export type RecoveryClass =
  'safe-to-continue' | 'safe-to-observe' | 'manual-reconciliation' | 'terminal';
export interface RecoveryRecord {
  table: string;
  id: string;
  state: string;
  classification: RecoveryClass;
  reason: string;
}
interface RecoverySource {
  table: string;
  id?: string;
  state?: string;
  terminal: readonly string[];
  local: readonly string[];
  locator?: string;
}
